  /// 全部分类的词条数
  static Map<String, int> counts() => {
        for (final section in sectionOrder)
          section: (_sections[section] ?? const {}).length,
      };

  /// 全部词条，按 [sectionOrder] 的顺序
  static List<TermEntry> all() => [
        for (final section in sectionOrder)
          for (final e in (_sections[section] ?? const {}).entries)
            TermEntry(section, e.key, e.value),
      ];

  /// 按关键字检索，词条名与释义都参与匹配；空关键字返回全部
  static List<TermEntry> search(String keyword) {
    final key = keyword.trim();
    if (key.isEmpty) return all();
    return [
      for (final e in all())
        if (e.term.contains(key) || e.meaning.contains(key)) e,
    ];
  }

  /// 检索结果按分类归拢，只保留有命中的分类，顺序仍按 [sectionOrder]
  static Map<String, List<TermEntry>> groupBySection(List<TermEntry> entries) {
    final out = <String, List<TermEntry>>{};
    for (final section in sectionOrder) {
      final list = entries.where((e) => e.section == section).toList();
      if (list.isNotEmpty) out[section] = list;
    }
    return out;
  }

  /// 取某个词的释义，没有则返回 null
  static String? meaningOf(String term) {
    for (final section in sectionOrder) {
      final hit = (_sections[section] ?? const {})[term];
      if (hit != null) return hit;
    }
    return null;
  }
