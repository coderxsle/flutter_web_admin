  /// 相对北京时间的校正分钟数，偏东为正
  static int offsetMinutes(double longitude) => ((longitude - 120) * 4).round();

  /// 校正后的出生时间
  static DateTime correct(DateTime local, double longitude) =>
      local.add(Duration(minutes: offsetMinutes(longitude)));

  /// 校正说明文案，如「−14 分钟」
  static String describe(double longitude) {
    final m = offsetMinutes(longitude);
    if (m == 0) return '与北京时间一致';
    return m > 0 ? '+$m 分钟' : '$m 分钟';
  }
