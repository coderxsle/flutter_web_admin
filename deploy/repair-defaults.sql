-- 数据库经 GUI 恢复后列默认值/序列丢失，本脚本按 definition.sql 补回。
-- 幂等：已有默认值的列 SET DEFAULT 只是重设同值，可重复执行。
-- 用法：psql -U postgres -d serverpod -v ON_ERROR_STOP=1 -f repair-defaults.sql

